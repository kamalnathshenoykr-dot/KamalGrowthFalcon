export const MENU_ITEMS: MenuItem[] = RAW_MENU_ITEMS.map((item) => {
  let isJain = false;
  let isVegan = item.isVeg && !['Dairy', 'Ghee', 'Paneer', 'Curd', 'Butter', 'Cheese', 'Milk', 'Payasam', 'Coffee'].some((w) => item.name.includes(w) || item.description.includes(w));
  let isGlutenFree = !['Paratha', 'Poori', 'Roti', 'Bun', 'Brownie', 'Kathi', 'Frankie', 'Idli'].some((w) => item.name.includes(w) || item.description.includes(w));
  let isNutFree = !['Cashew', 'Peanut', 'Nut', 'Almond', 'Pistachio', 'Nutty'].some((w) => item.name.includes(w) || item.description.includes(w));
  let allergens: string[] = [];
  if (['Ghee', 'Paneer', 'Curd', 'Butter', 'Cheese', 'Milk', 'Payasam', 'Coffee'].some((w) => item.name.includes(w) || item.description.includes(w))) allergens.push('Dairy');
  if (['Cashew', 'Peanut', 'Almond', 'Pistachio', 'Nutty'].some((w) => item.name.includes(w) || item.description.includes(w))) allergens.push('Nuts');
  if (['Paratha', 'Poori', 'Roti', 'Bun', 'Brownie', 'Kathi', 'Frankie'].some((w) => item.name.includes(w) || item.description.includes(w))) allergens.push('Gluten');
  if (item.name.includes('Tofu') || item.description.includes('edamame') || item.description.includes('sesame')) allergens.push('Soy');
  if (item.isVeg && !item.name.includes('Onion') && !item.description.includes('onion') && !item.name.includes('Garlic') && !item.description.includes('garlic')) {
    isJain = true;
  }
  let packagingRequired: MenuItem['packagingRequired'] = 'bagasse_box';
  if (item.name.includes('Flask') || item.category === 'Beverages') packagingRequired = 'flask_thermo';
  else if (item.name.includes('Bowl') || item.name.includes('Khichdi') || item.name.includes('Claypot') || item.name.includes('Payasam')) packagingRequired = 'paper_bowl';
  else if (item.name.includes('Biryani') || item.name.includes('Roll') || item.name.includes('Frankie')) packagingRequired = 'foil_container';

  return {
    ...item,
    isJain,
    isVegan,
    isGlutenFree,
    isNutFree,
    allergens: allergens.length > 0 ? allergens : ['Allergen-Free'],
    isSoldOut: item.id === 'tt-2' ? false : false,
    packagingRequired,
  };
});

